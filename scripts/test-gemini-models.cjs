const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const assert = require('node:assert/strict')
const root = path.join(__dirname, '..')
const source = fs.readFileSync(path.join(root, 'supabase/functions/_shared/ai.ts'), 'utf8')
const env = new Map()
const context = { exports: {}, Deno: { env: { get: name => env.get(name) } } }
vm.createContext(context)
vm.runInContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context)
const models = profile => Array.from(context.exports.geminiModels(profile))
for (const profile of ['deep', 'realtime']) assert.deepEqual(models(profile), ['gemini-3.8-flash', 'gemini-3.6-flash'])
env.set('GEMINI_MODEL', 'gemini-3.7-flash')
env.set('GEMINI_FALLBACK_MODEL', 'gemini-3.5-flash')
env.set('GEMINI_REALTIME_MODEL', 'gemini-3.7-flash')
env.set('GEMINI_REALTIME_FALLBACK_MODEL', 'gemini-3.5-flash')
for (const profile of ['deep', 'realtime']) assert.deepEqual(models(profile), ['gemini-3.8-flash', 'gemini-3.6-flash'])
env.set('GEMINI_DEEP_MODEL', 'custom-model')
assert.equal(models('deep')[0], 'custom-model', 'Explicit non-retired model overrides are preserved')
env.set('GEMINI_REALTIME_MODEL', 'gemini-3.6-flash')
assert.deepEqual(models('realtime'), ['gemini-3.6-flash'], 'Redirected duplicate fallback is removed')
for (const level of ['LOW', 'MEDIUM', 'HIGH']) assert.equal(context.exports.geminiThinkingConfig('deep', level).thinkingLevel, level)
assert.match(fs.readFileSync(path.join(root, 'supabase/functions/analyze-question/index.ts'), 'utf8'), /requestGemini\(requestBodyForModel\(\), 'realtime'\)/)
const live = fs.readFileSync(path.join(root, 'supabase/functions/gemini-caption-relay/index.ts'), 'utf8')
assert.match(live, /'gemini-3\.5-transcribe-live'/)
assert.match(live, /'gemini-3\.5-live-translate-preview'/)
console.log('PASS: 3.8 primary, 3.6 fallback, legacy overrides, deduplication, thinking levels and unchanged Live models')
